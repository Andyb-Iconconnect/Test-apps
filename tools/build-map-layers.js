/* -----------------------------------------------------------------------------
 * Regenerates data/world-borders.js and data/world-depth.js.
 *
 * Two layers beyond the coastline, in the same encoding, decoded by the same
 * Geo.decodeLand:
 *
 *   borders — international boundaries only, from Natural Earth 1:50m via the
 *             world-atlas package. Coastlines are excluded: the land layer
 *             already draws those, and doubling them thickens every shore.
 *
 *   depth   — the continental shelf and the 1000 m contour, from Natural Earth
 *             bathymetry. Published at 10m scale only, so it is simplified
 *             hard: this is a fleet board, not a navigation chart, and the
 *             shape of the shelf is the whole point rather than its detail.
 *
 * Run from the repository root:
 *
 *   npm pack world-atlas@2 topojson-client
 *   tar xzf world-atlas-*.tgz                       # -> package/countries-50m.json
 *   tar xzf topojson-client-*.tgz --one-top-level=tjc
 *   curl -O https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_10m_bathymetry_K_200.geojson
 *   curl -O https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_10m_bathymetry_J_1000.geojson
 *   node tools/build-map-layers.js
 *
 * Natural Earth is public domain. world-atlas is ISC.
 * -------------------------------------------------------------------------- */

const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const COUNTRIES = process.env.COUNTRIES_JSON || 'package/countries-50m.json';
const TOPOJSON = process.env.TOPOJSON_CLIENT || 'tjc/package/dist/topojson-client.js';
const SCALE = 500;             // ~220 m quantisation; ample for these two layers

/* --- Shared with build-coastline.js --------------------------------------- */

function ringArea(c) {
  let a = 0;
  for (let i = 0, n = c.length; i < n; i++) {
    const [x1, y1] = c[i], [x2, y2] = c[(i + 1) % n];
    a += x1 * y2 - x2 * y1;
  }
  return Math.abs(a / 2);
}

// Douglas-Peucker, iterative so a long contour cannot blow the stack.
function simplify(pts, eps) {
  if (pts.length < 3) return pts;
  const keep = new Uint8Array(pts.length);
  keep[0] = keep[pts.length - 1] = 1;
  const stack = [[0, pts.length - 1]];
  while (stack.length) {
    const [s, e] = stack.pop();
    const [sx, sy] = pts[s], [ex, ey] = pts[e];
    const dx = ex - sx, dy = ey - sy, len2 = dx * dx + dy * dy;
    let best = -1, bestDist = eps;
    for (let i = s + 1; i < e; i++) {
      const [px, py] = pts[i];
      let d;
      if (len2 === 0) {
        d = Math.hypot(px - sx, py - sy);
      } else {
        let t = ((px - sx) * dx + (py - sy) * dy) / len2;
        t = t < 0 ? 0 : t > 1 ? 1 : t;
        d = Math.hypot(px - (sx + t * dx), py - (sy + t * dy));
      }
      if (d > bestDist) { bestDist = d; best = i; }
    }
    if (best >= 0) { keep[best] = 1; stack.push([s, best], [best, e]); }
  }
  return pts.filter((_, i) => keep[i]);
}

const B64 = 'ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/';
function encodeVarint(n) {
  let zigzag = n < 0 ? -2 * n - 1 : 2 * n;
  let out = '';
  do {
    let digit = zigzag & 31;
    zigzag >>>= 5;
    if (zigzag > 0) digit |= 32;
    out += B64[digit];
  } while (zigzag > 0);
  return out;
}

// A ring crossing the antimeridian arrives wrapping from +180 to -180 mid-path.
// Drawn literally that single step spans the world and paints a bar across the
// chart. The renderer draws the world repeatedly, so unwrapped overspill lands
// in the neighbouring copy where it belongs.
function unwrapLongitudes(ring) {
  const out = [];
  let offset = 0;
  for (let i = 0; i < ring.length; i++) {
    if (i > 0) {
      const step = ring[i][0] - ring[i - 1][0];
      if (step > 180) offset -= 360;
      else if (step < -180) offset += 360;
    }
    out.push([ring[i][0] + offset, ring[i][1]]);
  }
  return out;
}

function encode(paths) {
  return paths.map((pts) => {
    let px = 0, py = 0;
    return pts.map(([lon, lat]) => {
      const x = Math.round(lon * SCALE), y = Math.round(lat * SCALE);
      const part = encodeVarint(x - px) + encodeVarint(y - py);
      px = x; py = y;
      return part;
    }).join('');
  }).join('|');
}

function write(file, globalName, encoded, note) {
  const body =
    '/* -----------------------------------------------------------------------------\n' +
    ' * ' + note + '\n' +
    ' *\n' +
    ' * Generated by tools/build-map-layers.js. Natural Earth, public domain.\n' +
    ' * Delta-encoded zigzag base-64 varints; decoded by Geo.decodeLand.\n' +
    ' * -------------------------------------------------------------------------- */\n\n' +
    'window.' + globalName + '_SCALE = ' + SCALE + ';\n' +
    'window.' + globalName + '_ENCODED =\n  "' + encoded + '";\n';
  fs.writeFileSync(path.join(ROOT, file), body);
  console.log(`${file}: ${Math.round(body.length / 1024)} KB`);
}

/* --- Borders --------------------------------------------------------------- */

function buildBorders() {
  if (!fs.existsSync(COUNTRIES) || !fs.existsSync(TOPOJSON)) {
    console.warn('Skipping borders: run the npm pack / tar commands in the header first.');
    return;
  }
  const topojson = require(path.resolve(TOPOJSON));
  const topo = JSON.parse(fs.readFileSync(COUNTRIES, 'utf8'));
  // The interior mesh: arcs shared by two different countries, which is exactly
  // the land boundaries and none of the coast.
  const mesh = topojson.mesh(topo, topo.objects.countries, (a, b) => a !== b);

  const lines = [];
  let raw = 0, kept = 0;
  for (const line of mesh.coordinates) {
    raw += line.length;
    const simplified = simplify(unwrapLongitudes(line), 0.02);
    if (simplified.length < 2) continue;
    kept += simplified.length;
    lines.push(simplified);
  }
  console.log(`borders: ${lines.length} lines, ${raw} -> ${kept} points`);
  write('data/world-borders.js', 'WORLD_BORDERS', encode(lines),
    'International boundaries. Coastlines are excluded — the land layer draws\n' +
    ' * those, and drawing them twice thickens every shore.');
}

/* --- Depth ----------------------------------------------------------------- */

// Two bands is the whole budget. The shelf is what makes a sea read as a sea;
// the 1000 m line gives the drop beyond it somewhere to go. Anything deeper is
// a uniform expanse that costs 190 KB to say nothing.
const DEPTH_BANDS = [
  { file: 'ne_10m_bathymetry_K_200.geojson', eps: 0.02, minArea: 0.02, label: '200 m' },
  { file: 'ne_10m_bathymetry_J_1000.geojson', eps: 0.03, minArea: 0.05, label: '1000 m' }
];

function buildDepth() {
  const present = DEPTH_BANDS.filter((b) => fs.existsSync(b.file));
  if (!present.length) {
    console.warn('Skipping depth: fetch the two bathymetry files named in the header.');
    return;
  }

  const chunks = [];
  const counts = [];
  for (const band of DEPTH_BANDS) {
    if (!fs.existsSync(band.file)) { counts.push(0); continue; }
    const geo = JSON.parse(fs.readFileSync(band.file, 'utf8'));
    const rings = [];
    for (const feature of geo.features) {
      const polygons = feature.geometry.type === 'Polygon'
        ? [feature.geometry.coordinates]
        : feature.geometry.coordinates;
      for (const polygon of polygons) {
        // Outer ring only. A hole in a depth band is an island or a deeper
        // basin, and at this simplification neither survives meaningfully.
        const ring = polygon[0];
        if (ringArea(ring) < band.minArea) continue;
        const simplified = simplify(unwrapLongitudes(ring), band.eps);
        if (simplified.length < 4) continue;
        rings.push(simplified);
      }
    }
    console.log(`depth ${band.label}: ${rings.length} rings`);
    counts.push(rings.length);
    chunks.push(encode(rings));
  }

  // Bands are concatenated and their ring counts recorded, so the renderer can
  // colour each band without a second file.
  write('data/world-depth.js', 'WORLD_DEPTH', chunks.join('|'),
    'Bathymetry: the continental shelf and the 1000 m contour.');
  fs.appendFileSync(path.join(ROOT, 'data/world-depth.js'),
    '\nwindow.WORLD_DEPTH_BANDS = ' + JSON.stringify(counts.filter((n) => n)) + ';\n');
}

buildBorders();
buildDepth();
